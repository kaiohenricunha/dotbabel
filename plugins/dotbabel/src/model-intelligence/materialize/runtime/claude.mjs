/** Claude-native projection rules over the shared resolver and pure materializer. */
import { resolve } from "../../resolver/index.mjs";
import { descriptor } from "../../sources/runtime/claude.mjs";
import { materialize } from "../index.mjs";
import { parseProjectionSource } from "../render.mjs";

// Native metadata only. Canonical taxonomy and the private dotbabel namespace stay at source.
const AGENT_KEYS = ["name", "description", "tools", "disallowedTools", "model", "effort", "permissionMode", "maxTurns", "skills", "mcpServers", "hooks", "memory", "background", "isolation", "initialPrompt", "omitClaudeMd", "autoCompactWindow"];
const SKILL_KEYS = ["name", "description", "when_to_use", "argument-hint", "arguments", "disable-model-invocation", "user-invocable", "allowed-tools", "context", "agent", "hooks", "paths", "license", "compatibility", "metadata"];
const COMMAND_KEYS = SKILL_KEYS.filter(key => !["name", "paths"].includes(key));
const fail = code => Object.assign(new Error(code), { code });

/**
 * Generate a Claude batch from canonical artifacts and caller-supplied offline evidence.
 * This pure boundary never discovers models or changes project/global activation.
 * @param {{toolVersion:string, artifacts:object[], context:object}} inputs Canonical bytes and existing resolver inputs.
 * @returns {{files:object[], manifest:object}} Native-only generated bytes and deterministic provenance.
 */
export function materializeClaude({ toolVersion, artifacts, context }) {
  if (!Array.isArray(artifacts) || !context) throw fail("claude_projection_input_invalid");
  const runtimeContract = context.runtimeContract ?? descriptor;
  return materialize({ toolVersion, artifacts: artifacts.map(artifact => {
    const kind = artifact.target?.artifactKind;
    if (!["agent", "command", "skill"].includes(kind)) throw fail("claude_projection_kind_invalid");
    const source = parseProjectionSource(artifact);
    const requirement = source.requirement;
    const target = { ...artifact.target, runtimeId: "claude" };
    const legacyAxes = artifact.legacyAxes;
    const invocation = legacyAxes ? { ...context.invocation, pin: { runtime: "claude", config: legacyAxes }, omitDefaultReasoning: true } : context.invocation;
    const resolverResult = resolve({ ...context, ...(invocation ? { invocation } : {}), requirement: requirement ?? undefined, target: { ...target, sourcePath: artifact.sourcePath }, runtimeContract });
    if (artifact.releaseBaseline === true && (legacyAxes || ["floor", "pin"].includes(requirement?.mode) || context.policy.floor !== undefined || resolverResult.explanation.some(entry => entry.code === "scoped_floor_applied")) && resolverResult.confidence === "low") throw fail("release_requirement_unsatisfied");
    const binding = (runtimeContract.capabilities ?? runtimeContract).binding?.[kind];
    if (requirement?.mode === "pin") {
      if (requirement.pin.runtime !== "claude") throw fail("claude_projection_pin_runtime");
      if (kind !== "skill" && Object.keys(requirement.pin.config).some(axis => binding?.support !== "supported" || binding.axes?.[axis] !== "supported" || kind === "command" && axis !== "model")) throw fail("claude_projection_pin_binding_unverified");
    }
    if (kind === "agent" && resolverResult.status === "resolved" && resolverResult.enforcement?.state !== "enforced") throw fail("claude_projection_agent_binding_unverified");
    const pinnedCommand = kind === "command" && (requirement?.mode === "pin" || legacyAxes?.model !== undefined);
    const dynamicBaseline = !legacyAxes && artifact.releaseBaseline === true && kind === "agent" && requirement?.mode === "dynamic" && context.policy.floor === undefined && !resolverResult.explanation.some(entry => entry.code === "scoped_floor_applied");
    const frontmatterKeys = kind === "agent" ? AGENT_KEYS : kind === "skill" ? SKILL_KEYS : [...COMMAND_KEYS, ...(pinnedCommand ? ["model"] : [])];
    const axisKeys = kind === "agent" ? { model: "model", reasoning: "effort" } : pinnedCommand ? { model: "model" } : {};
    return { ...artifact, target, requirement, policy: context.policy, resolverResult, runtimeContract,
      capabilityEvidence: artifact.capabilityEvidence ?? null,
      projectionContract: { ...(artifact.releaseBaseline === true ? { preferUnescapedQuotes: true } : {}), frontmatterKeys: dynamicBaseline ? frontmatterKeys.filter(key => !["model", "effort"].includes(key)) : frontmatterKeys, axisKeys: dynamicBaseline ? {} : axisKeys, allowExplicitPinAxes: pinnedCommand },
    };
  }) });
}
