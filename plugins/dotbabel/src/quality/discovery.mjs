import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

import { isRepoTrusted } from "../trust-allowlist.mjs";
import { matchesGlob } from "../spec-harness-lib.mjs";
import { QUALITY_ADAPTERS, getQualityAdapter } from "./adapters/registry.mjs";
import { capabilityInProfile, capabilityRules } from "./adapters/shared.mjs";

function inventory(repoRoot) {
  try {
    const tracked = execFileSync("git", ["-C", repoRoot, "ls-files", "-co", "--exclude-standard"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
    return [...new Set(tracked.split("\n").filter(Boolean))].sort();
  } catch {
    const files = [];
    function walk(dir) {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if ([".git", "node_modules", ".venv", "vendor"].includes(entry.name)) continue;
        const absolute = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(absolute);
        else if (entry.isFile()) files.push(path.relative(repoRoot, absolute).replaceAll(path.sep, "/"));
      }
    }
    walk(repoRoot);
    return files.sort();
  }
}

function applyExclusions(repoRoot, files, patterns) {
  const counts = new Map();
  const included = [];
  for (const file of files) {
    const pattern = patterns.find((candidate) => matchesGlob(candidate, file));
    let reason = pattern ? `policy pattern ${pattern}` : undefined;
    if (!reason) {
      try {
        const firstLines = fs.readFileSync(path.join(repoRoot, file), "utf8").split("\n").slice(0, 3).join("\n");
        if (/Code generated .* DO NOT EDIT|@generated|Autogenerated by/i.test(firstLines)) reason = "generated marker";
      } catch {}
    }
    if (reason) counts.set(reason, (counts.get(reason) ?? 0) + 1);
    else included.push(file);
  }
  return { files: included, exclusions: [...counts.entries()].map(([reason, count]) => ({ reason, count })).sort((a, b) => a.reason.localeCompare(b.reason)) };
}

function under(file, root) { return root === "." || file === root || file.startsWith(`${root}/`); }
function nearestRoot(file, components, language) {
  return components.filter((component) => component.language === language && under(file, component.root)).sort((a, b) => b.root.length - a.root.length)[0];
}

function readTsOptions(repoRoot, marker) {
  try {
    const text = fs.readFileSync(path.join(repoRoot, marker), "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    return JSON.parse(text).compilerOptions ?? {};
  } catch { return {}; }
}

function hasTsCheck(repoRoot, file) {
  try {
    return /(?:^|\n)\s*\/\/\s*@ts-check\b/.test(fs.readFileSync(path.join(repoRoot, file), "utf8").split("\n").slice(0, 5).join("\n"));
  } catch {
    return false;
  }
}

/** Detect language components and non-executing capability plans. */
export function detectQualityCapabilities({ repoRoot, policy = {} } = {}) {
  const filtered = applyExclusions(repoRoot, inventory(repoRoot), policy.exclude ?? []);
  const files = filtered.files;
  const discovered = QUALITY_ADAPTERS.flatMap((adapter) => adapter.discover({ root: repoRoot, files }));
  const byKey = new Map();
  for (const item of discovered) {
    const key = `${path.posix.normalize(item.root)}:${item.language}`;
    const previous = byKey.get(key);
    byKey.set(key, {
      ...previous,
      ...item,
      markers: [...new Set([...(previous?.markers ?? []), ...(item.markers ?? [])])].sort((a, b) => {
        const preferred = (marker) => path.basename(marker) === "tsconfig.json" ? 0 : 1;
        return preferred(a) - preferred(b) || a.localeCompare(b);
      }),
    });
  }
  for (const configured of policy.components ?? []) {
    const root = path.posix.normalize(configured.root);
    for (const language of configured.languages) {
      const key = `${root}:${language}`;
      byKey.set(key, { ...(byKey.get(key) ?? { root, language, markers: [] }), tools: configured.tools ?? {} });
    }
  }
  const components = [...byKey.values()].map((component) => ({
    ...component,
    id: `${component.root}:${component.language}`,
    absoluteRoot: path.resolve(repoRoot, component.root),
    files: files.filter((file) => under(file, component.root)),
    state: (getQualityAdapter(component.language) || Object.values(component.tools ?? {}).some((tool) => ["exit-code", "dotbabel-v1"].includes(tool.report?.format ?? "exit-code"))) ? "checked" : "unsupported",
    evidence: component.markers,
  }));
  const tsComponents = components.filter((component) => component.language === "typescript");
  for (const component of tsComponents) {
    const options = readTsOptions(repoRoot, component.markers[0]);
    const ownsJs = options.allowJs === true || options.checkJs === true;
    const ownedJavaScript = component.files.filter((file) => /\.[cm]?js$/.test(file) && (ownsJs || hasTsCheck(repoRoot, file)));
    component.files = component.files.filter((file) => !/\.[cm]?js$/.test(file) || ownedJavaScript.includes(file));
    for (const js of components.filter((item) => item.language === "javascript" && item.root === component.root)) {
      js.files = js.files.filter((file) => !ownedJavaScript.includes(file));
    }
  }
  for (const component of components) {
    component.files = component.files.filter((file) => nearestRoot(file, components, component.language)?.id === component.id);
  }
  components.sort((a, b) => a.id.localeCompare(b.id));
  const trust = isRepoTrusted({ repoRoot });
  return { repoRoot, files, components, trust, exclusions: filtered.exclusions, rejectedCandidates: [] };
}

/** Create adapter plans for a detected repository. */
export function planQualityCheck({ repoRoot, policy, changeSet, profile, detection } = {}) {
  const found = detection ?? detectQualityCapabilities({ repoRoot, policy });
  const plans = found.components.flatMap((component) => getQualityAdapter(component.language)?.plan(component, policy, changeSet, profile) ?? genericPlans(component, profile));
  return { ...found, plans };
}

function genericPlans(component, profile) {
  return Object.entries(component.tools ?? {}).filter(([capability]) => capabilityInProfile(capability, profile)).map(([capability, tool]) => ({ id: `${component.id}:${capability}`, componentId: component.id, capability, ruleIds: capabilityRules(capability), executable: tool.argv[0], argv: tool.argv.slice(1), cwd: component.absoluteRoot, timeoutSeconds: tool.timeout_seconds, report: tool.report, availability: "available", source: "project", requiresTrust: true }));
}
